def _hit(text, words):
    return any(w in text for w in words)


def classify(question):
    """返回该问题允许的最高能力等级。纯规则，不调模型。"""
    q = (question or "").strip()
    if not q:
        return OFF_TOPIC
    if _hit(q, OFF_TOPIC_HINTS):
        return OFF_TOPIC
    if not _hit(q, DOMAIN_WORDS):
        return OFF_TOPIC

    if _hit(q, SERVICE_WORDS):
        return L3_SERVICE

    if _hit(q, THRESHOLD_HINTS):
        return L2_MEDICAL
    if _hit(q, MEDICAL_STRONG):
        return L2_MEDICAL
    # "是不是比上次高了" 问的是变化，不该因为「是不是」被降成医学判断
    if _hit(q, MEDICAL_WEAK) and not _hit(q, TREND_HINTS) and not _hit(q, PREP_HINTS):
        return L2_MEDICAL

    if _hit(q, TREND_HINTS) or _hit(q, STRONG_EXPLAIN) or _hit(q, INTERPRET_WORDS):
        return L1_EXPLAIN
    if _hit(q, EXPLAIN_WORDS):
        # 「这个指标的单位是什么」问的是事实，不是解释
        return L0_DATA if _hit(q, DATA_WORDS) else L1_EXPLAIN
    if _hit(q, DATA_WORDS):
        return L0_DATA
    # 有领域词但看不出具体诉求（"帮我看看检查"），按解释给，信息量最大且仍不越界
    return L1_EXPLAIN


def is_tool_only(capability):
    """L0 只需要取数，不需要模型解释"""
    return capability == L0_DATA


def ceiling_hint(capability):
    return CEILINGS.get(capability, CEILINGS[L1_EXPLAIN])


def label(capability):
    return LABELS.get(capability, "")


def is_transaction(question):
    """要系统替他执行（挂号、问诊、缴费）→ 只给入口；只是咨询该去哪个科 → 可以推荐。"""
    return _hit((question or "").strip(), TRANSACTION_WORDS)


def is_off_topic(question):
    """没有领域词 = 与检查无关。宁可多引导一句，也不要硬凑答案。"""
    return classify(question) == OFF_TOPIC