def is_off_topic(question):
    """没有领域词 = 与检查无关。宁可多引导一句，也不要硬凑答案。"""
    q = (question or "").strip()
    if not q:
        return True
    if any(w in q for w in OFF_TOPIC_HINTS):
        return True
    return not any(w in q for w in DOMAIN_WORDS)
